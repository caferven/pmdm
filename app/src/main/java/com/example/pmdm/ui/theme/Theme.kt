/**
 * Tema de MiTienda. Todos los componentes toman sus colores de `MaterialTheme.colorScheme`
 * y sus estilos de texto de `MaterialTheme.typography`; nunca de valores escritos a mano.
 *
 * @param darkTheme `true` para usar la paleta oscura; por defecto sigue el ajuste del sistema.
 * @param dynamicColor si es `true` y el dispositivo es Android 12 (API 31) o superior, los colores se
 * toman del fondo de pantalla del usuario (*Material You*). En versiones anteriores, o si es `false`,
 * se usa la paleta propia de este archivo (*fallback*).
 */
@Composable
fun PMDMTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val colorScheme = when {
        // Build.VERSION_CODES.S = Android 12: la primera versión con colores dinámicos.
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content,
    )
}
